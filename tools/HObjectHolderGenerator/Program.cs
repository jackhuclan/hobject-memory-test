using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;

string dllPath = args.Length > 0 ? args[0] : Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../dlls/halcondotnetxl.dll"));
string outputPath = args.Length > 1 ? args[1] : Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../src/HObjectMemory.Lifetime/HObjectHolder.Generated.cs"));

if (!File.Exists(dllPath))
{
    Console.Error.WriteLine($"HALCON 托管程序集不存在：{dllPath}");
    return 1;
}

using FileStream stream = File.OpenRead(dllPath);
using PEReader peReader = new(stream);
MetadataReader reader = peReader.GetMetadataReader();
CsSignatureProvider provider = new();

List<GeneratedMethod> methods = [];
HashSet<string> emittedSignatures = new(StringComparer.Ordinal);
int skippedDuplicates = 0;

foreach (TypeDefinitionHandle typeHandle in reader.TypeDefinitions)
{
    TypeDefinition type = reader.GetTypeDefinition(typeHandle);
    if (GetFullName(reader, typeHandle) != "HalconDotNet.HOperatorSet")
    {
        continue;
    }

    foreach (MethodDefinitionHandle methodHandle in type.GetMethods())
    {
        MethodDefinition method = reader.GetMethodDefinition(methodHandle);
        string name = reader.GetString(method.Name);
        if (name is ".ctor" or ".cctor")
        {
            continue;
        }

        MethodSignature<string> signature;
        try
        {
            signature = method.DecodeSignature(provider, genericContext: null);
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"跳过无法解码签名的方法 {name}：{ex.Message}");
            continue;
        }

        List<OperatorParameter> parameters = [];
        foreach (ParameterHandle parameterHandle in method.GetParameters())
        {
            Parameter parameter = reader.GetParameter(parameterHandle);
            if (parameter.SequenceNumber == 0)
            {
                continue;
            }

            string rawType = signature.ParameterTypes[parameter.SequenceNumber - 1];
            parameters.Add(new OperatorParameter(
                reader.GetString(parameter.Name),
                rawType,
                (parameter.Attributes & ParameterAttributes.Out) != 0,
                (parameter.Attributes & ParameterAttributes.Optional) != 0));
        }

        if (!parameters.Any(p => IsHObjectOut(p)))
        {
            continue;
        }

        if (parameters.Any(p => p.IsOptional))
        {
            Console.Error.WriteLine($"跳过含可选参数的方法 {name}（需要额外语义确认）");
            continue;
        }

        if (parameters.Any(p => !p.IsSupported))
        {
            Console.Error.WriteLine($"跳过含不支持参数类型的方法 {name}：{string.Join(", ", parameters.Where(p => !p.IsSupported).Select(p => p.RawType))}");
            continue;
        }

        string returnType = ToCsType(signature.ReturnType);
        string publicSignature = $"{returnType} {name}({string.Join(", ", parameters.Select(p => p.IsHObjectOut ? $"out HObjectWeakHandle<HObject> {Escape(p.Name)}" : $"{(p.IsOut ? "out " : p.IsRef ? "ref " : "")}{ToCsType(p.RawType)} {Escape(p.Name)}"))})";
        if (!emittedSignatures.Add(publicSignature))
        {
            skippedDuplicates++;
            continue;
        }

        methods.Add(new GeneratedMethod(name, returnType, parameters));
    }
}

StringBuilder sb = new();
sb.AppendLine("// <auto-generated>");
sb.AppendLine("// 由 tools/HObjectHolderGenerator 根据 HalconDotNet.HOperatorSet 元数据生成。请勿手工修改。");
sb.AppendLine("// 重新生成：dotnet run --project tools/HObjectHolderGenerator -- <halcondotnetxl.dll> <输出文件>");
sb.AppendLine("// 生成规则：仅包装 out HObject 参数，其余返回类型、参数名、参数顺序和调用语义与原方法一致。");
sb.AppendLine("// </auto-generated>");
sb.AppendLine();
sb.AppendLine("using HalconDotNet;");
sb.AppendLine();
sb.AppendLine("namespace HObjectMemory.Lifetime;");
sb.AppendLine();
sb.AppendLine("public sealed partial class HObjectHolder");
sb.AppendLine("{");

foreach (GeneratedMethod method in methods)
{
    List<string> rawNames = method.Parameters.Select((p, i) => p.IsHObjectOut ? $"__hobjRaw{i}" : null).Where(n => n is not null).Select(n => n!).ToList();
    string rawArray = "new HObject[] { " + string.Join(", ", rawNames) + " }";
    List<string> publicParameters = [];
    List<string> callArguments = [];

    for (int i = 0; i < method.Parameters.Count; i++)
    {
        OperatorParameter p = method.Parameters[i];
        string escapedName = Escape(p.Name);
        string csType = p.IsHObjectOut
            ? "HObjectWeakHandle<HObject>"
            : ToCsType(p.RawType);
        string modifier = p.IsHObjectOut || p.IsOut ? "out " : p.IsRef ? "ref " : "";
        publicParameters.Add($"{modifier}{csType} {escapedName}");
        callArguments.Add(p.IsHObjectOut ? $"out __hobjRaw{i}" : $"{modifier}{escapedName}");
    }

    sb.AppendLine($"    // {method.Name}: 原方法 {string.Join(", ", method.Parameters.Select(p => p.RawType))}");
    sb.AppendLine($"    public {method.ReturnType} {Escape(method.Name)}({string.Join(", ", publicParameters)})");
    sb.AppendLine("    {");
    foreach (string rawName in rawNames)
    {
        sb.AppendLine($"        HObject {rawName} = new HObject();");
    }

    sb.AppendLine("        try");
    sb.AppendLine("        {");
    string invocation = $"HOperatorSet.{Escape(method.Name)}({string.Join(", ", callArguments)})";
    if (method.ReturnType == "void")
    {
        sb.AppendLine($"            {invocation};");
    }
    else
    {
        sb.AppendLine($"            var __hobjReturn = {invocation};");
    }

    sb.AppendLine($"            HObjectWeakHandle<HObject>[] __hobjWeak = TrackAll({rawArray}, \"{method.Name}\");");
    int weakIndex = 0;
    for (int i = 0; i < method.Parameters.Count; i++)
    {
        if (!method.Parameters[i].IsHObjectOut)
        {
            continue;
        }

        sb.AppendLine($"            {Escape(method.Parameters[i].Name)} = __hobjWeak[{weakIndex++}];");
    }

    if (method.ReturnType != "void")
    {
        sb.AppendLine("            return __hobjReturn;");
    }

    sb.AppendLine("        }");
    sb.AppendLine("        catch");
    sb.AppendLine("        {");
    sb.AppendLine($"            DisposeRawOutputs({rawArray});");
    foreach (OperatorParameter p in method.Parameters.Where(IsHObjectOut))
    {
        sb.AppendLine($"            {Escape(p.Name)} = HObjectWeakHandle<HObject>.Empty;");
    }

    sb.AppendLine("            throw;");
    sb.AppendLine("        }");
    sb.AppendLine("    }");
    sb.AppendLine();
}

sb.AppendLine("}");

Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
File.WriteAllText(outputPath, sb.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));

Console.WriteLine($"已生成 {methods.Count} 个包装方法：{outputPath}");
if (skippedDuplicates > 0)
{
    Console.WriteLine($"跳过重复签名 {skippedDuplicates} 个。");
}

return 0;

static bool IsHObjectOut(OperatorParameter p) => p.IsOut && p.RawType == "HalconDotNet.HObject&";

static string ToCsType(string rawType)
{
    return rawType switch
    {
        "void" => "void",
        "HalconDotNet.HObject&" => "HObject",
        "HalconDotNet.HTuple&" => "HTuple",
        "HalconDotNet.HObject" => "HObject",
        "HalconDotNet.HTuple" => "HTuple",
        _ when rawType.EndsWith('&') => ToCsType(rawType[..^1]),
        _ => rawType.StartsWith("global::", StringComparison.Ordinal) ? rawType : "global::" + rawType
    };
}

static string Escape(string identifier)
{
    HashSet<string> keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
        "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
        "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while"
    };

    return string.IsNullOrEmpty(identifier) || !keywords.Contains(identifier) ? identifier : "@" + identifier;
}

static string GetFullName(MetadataReader reader, TypeDefinitionHandle handle)
{
    TypeDefinition type = reader.GetTypeDefinition(handle);
    string name = reader.GetString(type.Name);
    TypeDefinitionHandle declaring = type.GetDeclaringType();
    if (!declaring.IsNil)
    {
        return GetFullName(reader, declaring) + "." + name;
    }

    string ns = reader.GetString(type.Namespace);
    return string.IsNullOrEmpty(ns) ? name : ns + "." + name;
}

internal sealed record OperatorParameter(string Name, string RawType, bool IsOut, bool IsOptional)
{
    public bool IsHObjectOut => IsOut && RawType == "HalconDotNet.HObject&";

    public bool IsRef => RawType.EndsWith('&') && !IsOut;

    public bool IsSupported => RawType is "HalconDotNet.HObject&" or "HalconDotNet.HTuple&" or "HalconDotNet.HObject" or "HalconDotNet.HTuple";
}

internal sealed record GeneratedMethod(string Name, string ReturnType, List<OperatorParameter> Parameters);

internal sealed class CsSignatureProvider : ISignatureTypeProvider<string, object?>
{
    public string GetArrayType(string elementType, ArrayShape shape) => elementType + "[" + new string(',', Math.Max(0, shape.Rank - 1)) + "]";
    public string GetByReferenceType(string elementType) => elementType + "&";
    public string GetFunctionPointerType(MethodSignature<string> signature) => "global::System.IntPtr";
    public string GetGenericInstantiation(string genericType, System.Collections.Immutable.ImmutableArray<string> typeArguments) => genericType + "<" + string.Join(", ", typeArguments) + ">";
    public string GetGenericMethodParameter(object? genericContext, int index) => "T" + index;
    public string GetGenericTypeParameter(object? genericContext, int index) => "T" + index;
    public string GetModifiedType(string modifier, string unmodifiedType, bool isRequired) => unmodifiedType;
    public string GetPinnedType(string elementType) => elementType;
    public string GetPointerType(string elementType) => elementType + "*";
    public string GetPrimitiveType(PrimitiveTypeCode typeCode) => typeCode switch
    {
        PrimitiveTypeCode.Void => "void",
        PrimitiveTypeCode.Boolean => "bool",
        PrimitiveTypeCode.Char => "char",
        PrimitiveTypeCode.SByte => "sbyte",
        PrimitiveTypeCode.Byte => "byte",
        PrimitiveTypeCode.Int16 => "short",
        PrimitiveTypeCode.UInt16 => "ushort",
        PrimitiveTypeCode.Int32 => "int",
        PrimitiveTypeCode.UInt32 => "uint",
        PrimitiveTypeCode.Int64 => "long",
        PrimitiveTypeCode.UInt64 => "ulong",
        PrimitiveTypeCode.Single => "float",
        PrimitiveTypeCode.Double => "double",
        PrimitiveTypeCode.String => "string",
        PrimitiveTypeCode.IntPtr => "nint",
        PrimitiveTypeCode.UIntPtr => "nuint",
        PrimitiveTypeCode.Object => "object",
        _ => throw new NotSupportedException($"不支持的原始类型 {typeCode}")
    };
    public string GetSZArrayType(string elementType) => elementType + "[]";
    public string GetTypeFromDefinition(MetadataReader r, TypeDefinitionHandle handle, byte rawTypeKind) => GetFullName(r, handle);
    public string GetTypeFromReference(MetadataReader r, TypeReferenceHandle handle, byte rawTypeKind)
    {
        TypeReference type = r.GetTypeReference(handle);
        string name = r.GetString(type.Name);
        string ns = r.GetString(type.Namespace);
        return string.IsNullOrEmpty(ns) ? name : ns + "." + name;
    }
    public string GetTypeFromSpecification(MetadataReader r, object? genericContext, TypeSpecificationHandle handle, byte rawTypeKind)
        => r.GetTypeSpecification(handle).DecodeSignature(this, genericContext);

    private static string GetFullName(MetadataReader r, TypeDefinitionHandle handle)
    {
        TypeDefinition type = r.GetTypeDefinition(handle);
        string name = r.GetString(type.Name);
        TypeDefinitionHandle declaring = type.GetDeclaringType();
        if (!declaring.IsNil)
        {
            return GetFullName(r, declaring) + "." + name;
        }

        string ns = r.GetString(type.Namespace);
        return string.IsNullOrEmpty(ns) ? name : ns + "." + name;
    }
}
